const { test } = require('node:test')
const assert = require('node:assert/strict')
const Y = require('yjs')
const { createHistory, copyContent, decodeVersion, publicVersion, versionContent } = require('../versionHistory.cjs')

function content(doc, title, text) {
  doc.transact(() => {
    doc.getMap('metadata').set('title', title)
    const rich = doc.getXmlFragment('richContent')
    rich.delete(0, rich.length)
    const paragraph = new Y.XmlElement('paragraph')
    const child = new Y.XmlText()
    child.insert(0, text, { bold: {} })
    paragraph.insert(0, [child])
    rich.insert(0, [paragraph])
    doc.getArray('board').push([{ color: '#123456', points: [{ x: .2, y: .7 }] }])
  }, { merhavUserId: 'alice' })
}

test('idle capture, nested formatting, deduplication and exclusion of workspace data', async () => {
  const doc = new Y.Doc()
  const record = { title: 'First' }
  let writes = 0
  const history = createHistory(record, doc, () => writes++, 30)
  assert.equal(record.versions.length, 1)
  content(doc, 'Edited', 'Hello')
  await new Promise(resolve => setTimeout(resolve, 60))
  assert.equal(record.versions.length, 2)
  assert.equal(record.versions[1].authorId, 'alice')
  assert.equal(record.title, 'Edited')
  history.capture()
  doc.getMap('workspace').set('areaId', 'outside-history')
  history.capture()
  assert.equal(record.versions.length, 2)
  const text = doc.getXmlFragment('richContent').get(0).get(0)
  text.format(0, 5, { italic: {} })
  await new Promise(resolve => setTimeout(resolve, 60))
  assert.equal(record.versions.length, 3)
  const named = history.capture('Milestone', 'named', 'alice')
  assert.equal(record.versions.length, 4)
  assert.equal(named.name, 'Milestone')
  assert.equal(publicVersion(named).state, undefined)
  const snapshot = decodeVersion(named)
  assert.deepEqual(snapshot.getXmlFragment('richContent').get(0).get(0).toDelta(), text.toDelta())
  assert.equal(snapshot.getMap('workspace').size, 0)
  snapshot.destroy()
  assert.equal(writes, 4)
  doc.destroy()
})

test('restore replaces newer content, preserves unrelated metadata and broadcasts as a normal CRDT update', () => {
  const doc = new Y.Doc()
  const record = { title: 'Initial' }
  const history = createHistory(record, doc, () => {})
  content(doc, 'Old title', 'Old text')
  doc.getText('content').insert(0, 'Legacy text')
  const old = history.capture('Old')
  const snapshot = decodeVersion(old)
  content(doc, 'New title', 'New text')
  doc.getText('content').delete(0, doc.getText('content').length)
  doc.getMap('metadata').set('unrelated', 'keep')
  history.capture(null, 'before-restore')
  const peer = new Y.Doc()
  Y.applyUpdate(peer, Y.encodeStateAsUpdate(doc))
  doc.on('update', update => Y.applyUpdate(peer, update))
  copyContent(snapshot, doc)
  history.capture(null, 'restored')
  assert.equal(peer.getXmlFragment('richContent').toString(), snapshot.getXmlFragment('richContent').toString())
  assert.deepEqual(peer.getArray('board').toArray(), snapshot.getArray('board').toArray())
  assert.equal(peer.getText('content').toString(), 'Legacy text')
  assert.equal(peer.getMap('metadata').get('title'), 'Old title')
  assert.equal(peer.getMap('metadata').get('unrelated'), 'keep')
  const recovery = decodeVersion(record.versions.at(-2))
  assert.match(recovery.getXmlFragment('richContent').toString(), /New text/)
  const branch = new Y.Doc()
  copyContent(snapshot, branch)
  assert.equal(branch.getXmlFragment('richContent').toString(), snapshot.getXmlFragment('richContent').toString())
  branch.getXmlFragment('richContent').delete(0, 1)
  assert.equal(snapshot.getXmlFragment('richContent').length, 1)
  recovery.destroy(); branch.destroy(); snapshot.destroy(); peer.destroy(); doc.destroy()
})

test('destroy captures pending edits, but document deletion does not recreate history', () => {
  for (const deleting of [false, true]) {
    const doc = new Y.Doc()
    const record = { title: 'First' }
    createHistory(record, doc, () => {})
    content(doc, 'Edited', 'Pending')
    record.deleting = deleting
    doc.destroy()
    assert.equal(record.versions.length, deleting ? 1 : 2)
  }
})

test('deduplication distinguishes literal markup from formatted text', () => {
  const doc = new Y.Doc()
  const record = { title: 'First' }
  const history = createHistory(record, doc, () => {})
  content(doc, 'First', 'Hello')
  const text = doc.getXmlFragment('richContent').get(0).get(0)
  const markup = text.toString()
  history.capture()
  text.delete(0, text.length)
  text.insert(0, markup)
  history.capture()
  assert.equal(record.versions.length, 3)
  doc.destroy()
})

test('comparison content preserves Unicode, line breaks, formatting and legacy text', () => {
  const doc = new Y.Doc()
  doc.getText('content').insert(0, 'Legacy text')
  assert.equal(versionContent(doc, 'Fallback').text, 'Legacy text')
  assert.equal(versionContent(doc, 'Fallback').title, 'Fallback')
  content(doc, 'כותרת', 'שלום <script>')
  const paragraph = doc.getXmlFragment('richContent').get(0)
  paragraph.insert(1, [new Y.XmlElement('hardBreak')])
  const tail = new Y.XmlText()
  tail.insert(0, 'Second line')
  paragraph.insert(2, [tail])
  const preview = versionContent(doc)
  assert.equal(preview.text, 'שלום <script>\nSecond line')
  assert.equal(preview.title, 'כותרת')
  const structure = JSON.parse(preview.structure)
  assert.deepEqual(structure[0].children[0].text[0].attributes, { bold: {} })
  assert.equal(preview.board.length, 1)
  assert.equal(preview.state, undefined)
  doc.destroy()
})
